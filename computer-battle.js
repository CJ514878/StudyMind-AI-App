/* =========================================================
   AUTHENTICATION CHECK
========================================================= */

async function verifyComputerBattleUser() {

    const client =
        await waitForSupabaseClient();


    if (!client) {

        throw new Error(
            "Supabase client could not be loaded."
        );

    }


    const {
        data: {
            user
        },
        error
    } =
        await client.auth.getUser();


    if (error) {
        throw error;
    }


    if (!user) {

        throw new Error(
            "You must be logged in to play Computer Battle."
        );

    }


    battleState.user =
        user;


    return user;

}


