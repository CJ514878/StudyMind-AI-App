async function waitForSupabaseClient(timeout = 10000) {

    const start = Date.now();

    while (Date.now() - start < timeout) {

        const client = getComputerBattleSupabase();

        if (client) {
            return client;
        }

        await new Promise(resolve => {
            setTimeout(resolve, 100);
        });

    }

    return null;

}


/* =========================================================
   TEXT UTILITIES
========================================================= */

function cleanText(value) {

    if (value === null || value === undefined) {
        return "";
    }

    return String(value)
        .replace(/\s+/g, " ")
        .trim();

}


function normalizeSubjectName(subject) {

    const value = cleanText(subject);

    if (!value) {
        return "";

    }

    const key = value.toLowerCase();

    return SUBJECT_ALIASES[key] || value;

}


function normalizeTopicName(topic) {

    return cleanText(topic);

}


/* =========================================================
   CURRICULUM HELPERS
========================================================= */

function getCurriculumSubjects() {

    return Object.keys(NIGERIAN_CURRICULUM)
        .sort((a, b) => a.localeCompare(b));

}


function findCurriculumSubject(subject) {

    const normalized = normalizeSubjectName(subject);

    const exact = Object.keys(NIGERIAN_CURRICULUM)
        .find(item =>
            item.toLowerCase() === normalized.toLowerCase()
        );

    if (exact) {
        return exact;
    }

    return normalized;

}


function getCurriculumTopics(subject) {

    const curriculumSubject =
        findCurriculumSubject(subject);

    return NIGERIAN_CURRICULUM[curriculumSubject] || [];

}


/* =========================================================
   STUDY PLAN
========================================================= */

function getStudyPlan() {

    const possibleKeys = [

        "studyMindPlan",

        "studyData",

        "studyPlan",

        "studyMindStudyPlan"

    ];

    for (const key of possibleKeys) {

        try {

            const raw =
                localStorage.getItem(key);

            if (!raw) {
                continue;
            }

            const parsed =
                JSON.parse(raw);

            if (parsed) {
                return parsed;
            }

        } catch (error) {

            console.warn(
                `Unable to read ${key}`,
                error
            );

        }

    }

    return null;

}


/* =========================================================
   PLAN SUBJECT EXTRACTION
========================================================= */

function getPlanSubjects(plan) {

    if (!plan) {
        return [];
    }

    const subjects = [];

    const possibleArrays = [

        plan.subjects,

        plan.subjectList,

        plan.data?.subjects,

        plan.studyPlan?.subjects,

        plan.schedule?.subjects

    ];

    for (const list of possibleArrays) {

        if (!Array.isArray(list)) {
            continue;
        }

        for (const item of list) {

            if (typeof item === "string") {

                const name =
                    normalizeSubjectName(item);

                if (name) {
                    subjects.push(name);
                }

            }

            else if (
                item &&
                typeof item === "object"
            ) {

                const name =
                    item.subject ||
                    item.name ||
                    item.title;

                if (name) {

                    const normalized =
                        normalizeSubjectName(name);

                    if (normalized) {
                        subjects.push(normalized);
                    }

                }

            }

        }

    }

    return [
        ...new Set(subjects)
    ];

}


/* =========================================================
   TOPICS FROM STUDY PLAN
========================================================= */

function getPlanTopics(plan, selectedSubject) {

    if (!plan) {
        return [];
    }

    const topics = [];

    const normalizedSelectedSubject =
        normalizeSubjectName(selectedSubject);

    const possibleArrays = [

        plan.topics,

        plan.studyTopics,

        plan.studyPlan?.topics,

        plan.data?.topics,

        plan.schedule?.topics

    ];

    for (const list of possibleArrays) {

        if (!Array.isArray(list)) {
            continue;
        }

        for (const item of list) {

            if (typeof item === "string") {

                const topic =
                    normalizeTopicName(item);

                if (topic) {
                    topics.push(topic);
                }

                continue;

            }


            if (
                item &&
                typeof item === "object"
            ) {

                const itemSubject =
                    normalizeSubjectName(
                        item.subject ||
                        item.subjectName ||
                        item.course ||
                        ""
                    );

                const topic =
                    item.topic ||
                    item.name ||
                    item.title;

                if (!topic) {
                    continue;
                }

                /*
                 * If the topic explicitly belongs to a
                 * subject, only include it for that subject.
                 */

                if (
                    itemSubject &&
                    normalizedSelectedSubject &&
                    itemSubject !== normalizedSelectedSubject
                ) {
                    continue;
                }

                topics.push(
                    normalizeTopicName(topic)
                );

            }

        }

    }

    return [
        ...new Set(
            topics.filter(Boolean)
        )
    ];

}


/* =========================================================
   GET AVAILABLE SUBJECTS
========================================================= */

function getAvailableSubjects(plan) {

    const subjects = [

        ...getCurriculumSubjects(),

        ...getPlanSubjects(plan)

    ];

    return [
        ...new Set(
            subjects
                .map(normalizeSubjectName)
                .filter(Boolean)
        )
    ].sort(
        (a, b) => a.localeCompare(b)
    );

}


/* =========================================================
   GET AVAILABLE TOPICS
========================================================= */

function getAvailableTopics(plan, subject) {

    const curriculumTopics =
        getCurriculumTopics(subject);

    const planTopics =
        getPlanTopics(plan, subject);

    return [
        ...new Set([
            ...curriculumTopics,
            ...planTopics
        ])
    ].filter(Boolean);

}


