function getBattleCountKey() {

    const userId =
        battleState.user?.id ||
        "guest";


    return `studyMindComputerBattles_${userId}`;

}


function getBattleCount() {

    try {

        return Number(
            localStorage.getItem(
                getBattleCountKey()
            ) || 0
        );

    } catch {

        return 0;

    }

}


function incrementBattleCount() {

    try {

        const next =
            getBattleCount() + 1;


        localStorage.setItem(
            getBattleCountKey(),
            String(next)
        );


        return next;

    } catch {

        return 0;

    }

}


